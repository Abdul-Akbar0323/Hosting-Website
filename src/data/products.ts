export const getProductBySlug = (slug: string): Product | undefined => {
  return products.find(p => p.slug === slug);
};

export const getProductsByCategory = (category: string): Product[] => {
  return products.filter(p => p.category === category);
};

export const getProductsByCollection = (collection: string): Product[] => {
  return products.filter(p => p.collection.includes(collection));
};

export const getFeaturedProducts = (): Product[] => {
  return products.filter(p => p.featured);
};

export const getBestsellers = (): Product[] => {
  return products.filter(p => p.bestseller);
};

export const getNewArrivals = (): Product[] => {
  return products.filter(p => p.newArrival);
};

export const getSaleProducts = (): Product[] => {
  return products.filter(p => p.discount !== null);
};

export const getRelatedProducts = (productId: string, limit: number = 4): Product[] => {
  const product = products.find(p => p.id === productId);
  if (!product) return [];
  return products
    .filter(p => p.id !== productId && (p.category === product.category || p.collection.some(c => product.collection.includes(c))))
    .slice(0, limit);
};

export const getProductReviews = (productId: string): Review[] => {
  return reviews.filter(r => r.productId === productId);
};